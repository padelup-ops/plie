import UIKit

/// Le presse-papier du clavier : ce que tu copies dans n'importe quelle app, gardé sur le téléphone (jamais envoyé),
/// pour le recoller plus tard. iOS ne laisse un clavier lire le presse-papier qu'avec l'accès complet, et seulement
/// pendant qu'il est affiché : on regarde quand il apparaît, puis toutes les secondes tant qu'il reste à l'écran.
final class KBClipboard {
    static let shared = KBClipboard()

    struct Item: Codable, Equatable {
        var text: String
        var date: Date
        var pinned: Bool
    }

    private let key = "foldboard.clipboard.v1"
    private let changeKey = "foldboard.clipboard.change"
    private(set) var items: [Item] = []
    /// Le dernier élément copié, tant qu'il est récent et pas encore collé : proposé dans la barre.
    private(set) var fresh: Item?
    private var lastChange: Int
    private static let maxItems = 30
    /// Les éléments non épinglés s'effacent seuls au bout de 3 jours (épinglés : gardés).
    private static let lifetime: TimeInterval = 3 * 24 * 3600
    /// Texte gardé au maximum (un très long texte copié est coupé).
    private static let maxLength = 5_000
    /// Types posés par les gestionnaires de mots de passe : jamais gardés.
    private static let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private init() {
        lastChange = UserDefaults.standard.integer(forKey: changeKey)
        if let d = UserDefaults.standard.data(forKey: key), let list = try? JSONDecoder().decode([Item].self, from: d) {
            items = list
        }
        prune()
    }

    /// Regarde si quelque chose de nouveau a été copié. Renvoie vrai s'il y a un nouvel élément.
    @discardableResult
    func capture() -> Bool {
        let pb = UIPasteboard.general
        let change = pb.changeCount
        guard change != lastChange else { return false }
        lastChange = change
        UserDefaults.standard.set(change, forKey: changeKey)
        // Un mot de passe copié depuis un gestionnaire : on ne le garde pas.
        if pb.types.contains(where: { Self.privateTypes.contains($0) }) { return false }
        guard pb.hasStrings, var text = pb.string else { return false }
        if text.hasPrefix("FOLDBOARD-GRIPLOG:") { return false }
        text = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return false }
        if text.count > Self.maxLength { text = String(text.prefix(Self.maxLength)) }
        let pinned = items.first(where: { $0.text == text })?.pinned ?? false
        items.removeAll { $0.text == text }
        let item = Item(text: text, date: Date(), pinned: pinned)
        items.insert(item, at: 0)
        fresh = item
        prune()
        save()
        return true
    }

    /// Captures de l'App Store : une liste d'exemple.
    func seedForShots(_ texts: [String]) {
        items = texts.enumerated().map { Item(text: $0.element, date: Date().addingTimeInterval(-Double($0.offset) * 600), pinned: $0.offset == 1) }
        fresh = nil
    }

    /// Le dernier copié est récent (moins de 3 minutes) : on le propose dans la barre.
    var freshText: String? {
        guard let f = fresh, Date().timeIntervalSince(f.date) < 180 else { return nil }
        return f.text
    }

    /// Collé ou écarté : il ne revient plus dans la barre.
    func dismissFresh() { fresh = nil }

    func togglePin(_ text: String) {
        guard let i = items.firstIndex(where: { $0.text == text }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func remove(_ text: String) {
        items.removeAll { $0.text == text }
        if fresh?.text == text { fresh = nil }
        save()
    }

    /// Efface tout sauf les éléments épinglés.
    func clearUnpinned() {
        items.removeAll { !$0.pinned }
        fresh = nil
        save()
    }

    private func prune() {
        let now = Date()
        items.removeAll { !$0.pinned && now.timeIntervalSince($0.date) > Self.lifetime }
        // Les épinglés d'abord dans la limite, puis les plus récents.
        if items.count > Self.maxItems {
            var keep = items.filter(\.pinned)
            for it in items where !it.pinned && keep.count < Self.maxItems { keep.append(it) }
            items = items.filter { keep.contains($0) }
        }
    }

    private func save() {
        if let d = try? JSONEncoder().encode(items) { UserDefaults.standard.set(d, forKey: key) }
    }
}

/// La liste du presse-papier, à la place des emojis : touche un élément pour le coller, épingle ceux à garder.
final class ClipboardList: UIView {
    var onPaste: ((String) -> Void)?
    var textColor: UIColor = .label { didSet { reload() } }
    var keyColor: UIColor = .systemGray4 { didSet { reload() } }
    var accent: UIColor = .systemBlue { didSet { reload() } }
    var fullAccess = true { didSet { if oldValue != fullAccess { reload() } } }

    private let scroll = DragScroll()
    private var builtFor: CGSize = .zero

    override init(frame: CGRect) {
        super.init(frame: frame)
        scroll.alwaysBounceVertical = true
        scroll.showsVerticalScrollIndicator = false
        scroll.delaysContentTouches = false
        addSubview(scroll)
    }

    required init?(coder: NSCoder) { fatalError() }

    override func layoutSubviews() {
        super.layoutSubviews()
        scroll.frame = bounds
        if bounds.size != builtFor { reload() }
    }

    func reload() {
        builtFor = bounds.size
        scroll.subviews.forEach { $0.removeFromSuperview() }
        let w = bounds.width
        guard w > 40 else { return }
        if !fullAccess {
            message(L("Turn on Full Access in Settings › Foldboard to keep what you copy here. It stays on your iPhone."))
            return
        }
        let items = KBClipboard.shared.items
        if items.isEmpty {
            message(L("Copy text in any app and it shows up here, ready to paste."))
            return
        }
        var y: CGFloat = 4
        // En tête : tout effacer (les épinglés restent).
        if items.contains(where: { !$0.pinned }) {
            let clear = UIButton(type: .system)
            clear.setTitle(L("Clear"), for: .normal)
            clear.titleLabel?.font = .systemFont(ofSize: 13, weight: .semibold)
            clear.tintColor = textColor.withAlphaComponent(0.7)
            clear.sizeToFit()
            clear.frame = CGRect(x: w - clear.bounds.width - 16, y: y, width: clear.bounds.width + 8, height: 24)
            clear.addAction(UIAction { [weak self] _ in KBClipboard.shared.clearUnpinned(); self?.reload() }, for: .touchUpInside)
            scroll.addSubview(clear)
            let title = UILabel(frame: CGRect(x: 8, y: y, width: w - 100, height: 24))
            title.text = L("Clipboard")
            title.font = .systemFont(ofSize: 13, weight: .semibold)
            title.textColor = textColor.withAlphaComponent(0.6)
            scroll.addSubview(title)
            y += 28
        }
        // Des cartes en grille (comme le presse-papier Samsung) : plus de texte visible, plus facile à viser.
        let cols = max(2, min(4, Int((w - 8) / 140)))
        let gap: CGFloat = 6
        let cardW = (w - 8 - gap * CGFloat(cols - 1)) / CGFloat(cols)
        let cardH: CGFloat = 92
        for (n, it) in items.enumerated() {
            let col = n % cols, row = n / cols
            let card = UIView(frame: CGRect(x: 4 + CGFloat(col) * (cardW + gap), y: y + CGFloat(row) * (cardH + gap), width: cardW, height: cardH))
            card.backgroundColor = keyColor
            card.layer.cornerRadius = 12
            card.layer.cornerCurve = .continuous
            if it.pinned {
                card.layer.borderWidth = 1.5
                card.layer.borderColor = accent.withAlphaComponent(0.7).cgColor
            }
            let paste = UIButton(type: .custom)
            paste.frame = card.bounds
            paste.addAction(UIAction { [weak self] _ in self?.onPaste?(it.text) }, for: .touchUpInside)
            paste.accessibilityLabel = it.text
            card.addSubview(paste)
            let label = UILabel(frame: CGRect(x: 10, y: 8, width: cardW - 20, height: cardH - 36))
            label.text = it.text.replacingOccurrences(of: "\n", with: " ")
            label.numberOfLines = 3
            label.lineBreakMode = .byTruncatingTail
            label.font = .systemFont(ofSize: 13)
            label.textColor = textColor
            label.isUserInteractionEnabled = false
            label.sizeToFit()
            label.frame.size.width = cardW - 20
            label.frame.size.height = min(label.frame.height, cardH - 36)
            card.addSubview(label)
            let small = UIImage.SymbolConfiguration(pointSize: 12, weight: .semibold)
            let pin = UIButton(type: .system)
            pin.setImage(UIImage(systemName: it.pinned ? "pin.fill" : "pin", withConfiguration: small), for: .normal)
            pin.tintColor = it.pinned ? accent : textColor.withAlphaComponent(0.5)
            pin.frame = CGRect(x: cardW - 68, y: cardH - 30, width: 32, height: 28)
            pin.accessibilityLabel = it.pinned ? L("Unpin") : L("Pin")
            pin.addAction(UIAction { [weak self] _ in KBClipboard.shared.togglePin(it.text); self?.reload() }, for: .touchUpInside)
            card.addSubview(pin)
            let del = UIButton(type: .system)
            del.setImage(UIImage(systemName: "xmark", withConfiguration: small), for: .normal)
            del.tintColor = textColor.withAlphaComponent(0.5)
            del.frame = CGRect(x: cardW - 36, y: cardH - 30, width: 32, height: 28)
            del.accessibilityLabel = L("Delete")
            del.addAction(UIAction { [weak self] _ in KBClipboard.shared.remove(it.text); self?.reload() }, for: .touchUpInside)
            card.addSubview(del)
            scroll.addSubview(card)
        }
        let rowsN = (items.count + cols - 1) / cols
        y += CGFloat(rowsN) * (cardH + gap)
        scroll.contentSize = CGSize(width: w, height: y + 4)
    }

    private func message(_ text: String) {
        let l = UILabel(frame: bounds.insetBy(dx: 20, dy: 10))
        l.text = text
        l.numberOfLines = 0
        l.textAlignment = .center
        l.font = .systemFont(ofSize: 14)
        l.textColor = textColor.withAlphaComponent(0.6)
        scroll.addSubview(l)
        scroll.contentSize = bounds.size
    }
}

/// Une liste qui défile même quand le doigt part d'un bouton (sinon, partir d'un élément bloquait le défilement).
final class DragScroll: UIScrollView {
    override func touchesShouldCancel(in view: UIView) -> Bool { true }
}
